import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {newToken,invitationPayload,linkForToken,tokenFromHash,localInviteKey} from "../scripts/private-invitation.mjs";
const example={id:"A1B2C3D4-1111-4111-8111-111111111111",
 url:"https://dbv.turnier.de/tournament/A1B2C3D4-1111-4111-8111-111111111111",
 name:"Jugend-RLT",playerId:"05-070879",startDate:"2026-12-03",endDate:"2026-12-04"};
const token=newToken({getRandomValues:arr=>{arr.forEach((_,i)=>arr[i]=i);return arr}});
assert.equal(token.length,64);
assert.match(token,/^[0-9a-f]{64}$/);
assert.equal(token.slice(0,8),"00010203");
const p=invitationPayload(example,token);
assert.deepEqual(Object.keys(p).sort(),["p_end_date","p_source_url","p_start_date","p_title","p_token"].sort());
assert(!JSON.stringify(p).includes("05-070879"),"Never publish player ID");
assert.equal(p.p_start_date,"2026-12-03");
const uri=linkForToken("https://metzgerhannes-oss.github.io/Badminton/index.html#turniere",token);
assert.equal(new URL(uri).pathname,"/Badminton/private-invite.html");
assert.equal(new URL(uri).search,"");
assert.equal(tokenFromHash(new URL(uri).hash),token);
assert.equal(tokenFromHash("#t=invalid"),"");
assert.equal(localInviteKey(example),example.id+"|05-070879");
assert.throws(()=>invitationPayload({...example,startDate:""},token),/Turnierdatum/);
assert.throws(()=>invitationPayload({...example,url:"https://evil.example/"},token),/Turnierquellen/);
assert.throws(()=>invitationPayload({...example,url:"javascript:alert(1)"},token),/Turnierquellen/);
assert.throws(()=>invitationPayload({...example,endDate:"2029-02-01"},token),/Turnierdatum/);
const sql=await readFile("database/private-tournament-invites-v108.sql","utf8");
const js=await readFile("private-invites.js","utf8");
const reader=await readFile("private-invite-page.js","utf8");
const page=await readFile("private-invite.html","utf8");
const index=await readFile("index.html","utf8");
assert.match(sql,/ENABLE ROW LEVEL SECURITY/);
assert.match(sql,/REVOKE ALL ON public.private_tournament_invites FROM PUBLIC,anon,authenticated/);
assert.match(sql,/owner_user_id=auth.uid\(\)/);
assert.match(sql,/extensions.digest/);
assert.match(sql,/LIMIT 1/);
assert.match(sql,/expires_at>now\(\)/);
assert.match(sql,/created_at>now\(\)-interval '24 hours'/);
assert.match(sql,/GRANT EXECUTE ON FUNCTION public.private_tournament_invite_read\(text\) TO anon,authenticated/);
assert.doesNotMatch(sql,/GRANT SELECT .*private_tournament_invites TO anon|GRANT INSERT .*private_tournament_invites TO anon/i);
assert.match(js,/async function create\(\)/);
assert.match(js,/if\(!create\)return null/);
assert.match(js,/rpc\/private_tournament_invite_create/);
assert.match(js,/rpc\/private_tournament_invite_revoke/);
assert.match(reader,/history.replaceState\(null/);
assert.match(reader,/rpc\/private_tournament_invite_read/);
assert.match(page,/no-referrer/);
assert.match(index,/id="private-share-create"/);
console.log("Private invitation security contract: one event, 256-bit token, 7-day expiry, owner revocation, no login for readers.");
