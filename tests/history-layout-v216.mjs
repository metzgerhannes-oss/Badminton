import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
const [html,history,external]=await Promise.all(["index.html","history.js","external-matches.js"].map(f=>readFile(f,"utf8")));
const home=html.slice(html.indexOf('id="view-start"'),html.indexOf('id="view-historie"'));
const view=html.slice(html.indexOf('id="view-historie"'),html.indexOf('id="view-turniere"'));
const idx=s=>view.indexOf(s);
assert.match(home,/<a class="home-stats-link" href="#historie">Komplette Statistik<\/a>/);
assert.match(view,/<a class="history-inline-link" href="#start">Zurück zur Übersicht<\/a>/);
assert.ok(idx('class="trophy-section"')<idx('id="history-source-details"'));
assert.ok(idx('class="trophy-section"')<idx('id="history-timeline"'));
assert.ok(idx('class="history-ranking-note"')<idx('id="career-history"'));
assert.ok(idx('id="career-history"')<idx('id="external-match-history"'));
assert.equal((view.match(/id="trophy-shelf"/g)||[]).length,1);
assert.equal((view.match(/id="external-match-progress"/g)||[]).length,1);
assert.match(view,/<details id="external-match-source-details"/);
assert.doesNotMatch(view,/<details id="external-match-source-details"[^>]*open/);
assert.match(view,/<summary>Quellenstand und Abweichungen anzeigen<\/summary>/);
assert.match(view,/id="external-match-brief"/);
assert.match(view,/id="external-match-retry"/);
assert.match(view,/id="history-source-coverage"[^>]*hidden/);
assert.match(history,/coverage\.hidden=true/);
assert.match(history,/state\.coverage==="sourced_placements_partial"/);
assert.match(history,/if\(error\)\{source\.hidden=false/);
assert.match(external,/brief\.hidden=false/);
assert.match(external,/retry\.hidden=!failed/);
assert.match(external,/progressEl\.textContent=privateMode/);
console.log("UX v216: trophies first, compact navigation, collapsible source details and errors visible.");
