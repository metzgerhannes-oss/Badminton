import assert from 'node:assert/strict';
import {WIDTH,HEIGHT,DURATION_MS,MODE_VERSION,PADDLE_HEIGHT,BALL_RADIUS,newPong,movePaddle,tickPong} from '../games/pong.mjs';
assert.equal(WIDTH,400);assert.equal(HEIGHT,240);assert.equal(DURATION_MS,90000);assert.equal(MODE_VERSION,1);
const start=newPong();assert.equal(start.score,0);assert.equal(start.misses,0);
assert.equal(movePaddle(start,-100).playerY,0);assert.equal(movePaddle(start,1000).playerY,HEIGHT-PADDLE_HEIGHT);
assert.equal(start.playerY,(HEIGHT-PADDLE_HEIGHT)/2,'pure movement never mutates');
assert.equal(tickPong(start,0),start);
const top=tickPong({...start,ballX:200,ballY:BALL_RADIUS+1,vx:-1,vy:-5},16);
assert.ok(top.vy>0);assert.ok(top.ballY>=BALL_RADIUS);
const bottom=tickPong({...start,ballX:200,ballY:HEIGHT-BALL_RADIUS-1,vx:1,vy:5},16);
assert.ok(bottom.vy<0);assert.ok(bottom.ballY<=HEIGHT-BALL_RADIUS);
const left=tickPong({...start,playerY:85,ballX:39,ballY:110,vx:-14,vy:0},16);
assert.equal(left.score,1);assert.ok(left.vx>0);assert.equal(tickPong(left,16).score,1);
const miss=tickPong({...start,playerY:0,ballX:-7,ballY:210,vx:-4,vy:0},16);
assert.equal(miss.misses,1);assert.equal(miss.score,0);assert.equal(miss.ballX,WIDTH/2);
const bot=tickPong({...start,ballX:365,ballY:start.botY+20,vx:16,vy:0},16);
assert.ok(bot.vx<0);assert.equal(bot.score,0);
assert.equal(tickPong(start,Infinity),start);
assert.ok(Math.abs(tickPong(start,10000).ballX-start.ballX)<10);
console.log('Pong physics: scoring, bot, misses, walls and bounds OK');
