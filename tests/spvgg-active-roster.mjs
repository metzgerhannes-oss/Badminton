import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {validateSpvggRoster,rosterGroups,rosterHtml,rosterMatchesClub,loadSpvggRoster} from "../scripts/spvgg-roster.mjs";
const doc=JSON.parse(readFileSync(new URL("../data/spvgg-active-roster.json",import.meta.url)));
assert.equal(validateSpvggRoster(doc),doc);
assert.equal(doc.teams.length,5);
assert.equal(doc.sourceSeason,"2025/26");
assert.equal(new Set(doc.teams.flatMap(t=>t.members)).size,45);
assert.equal(doc.teams.flatMap(t=>t.members).length,50);
assert.equal(rosterGroups(doc).length,5);
assert.equal(rosterGroups(doc,{team:"III"}).length,1);
assert.ok(rosterGroups(doc,{query:"Sarah Storz"}).some(t=>t.members.includes("Sarah Storz")));
assert.ok(rosterGroups(doc,{query:"Natalya"}).length===2);
assert.equal(rosterGroups(doc,{query:"Fiktiver Name"}).length,0);
assert.equal(rosterMatchesClub("SpVgg. Mössingen"),true);
assert.equal(rosterMatchesClub("SpVgg Moessingen"),true);
assert.equal(rosterMatchesClub("TSV Tübingen"),false);
assert.match(rosterHtml(doc,{team:"I"}),/Bent Julian Meyer/);
assert.doesNotMatch(rosterHtml(doc,{team:"II"}),/Bent Julian Meyer/);
assert.equal(rosterHtml(doc,{query:"Sondername"}).includes("Keine passenden Spieler"),true);
assert.throws(()=>validateSpvggRoster({...doc,teams:doc.teams.slice(0,4)}));
assert.throws(()=>validateSpvggRoster({...doc,teams:doc.teams.map((t,i)=>i===0?{...t,members:["<script>"]}:t)}));
assert.throws(()=>validateSpvggRoster({...doc,teams:doc.teams.map((t,i)=>i===0?{...t,sourceUrl:"https://example.org"}:t)}));
const read=await loadSpvggRoster({fetchImpl:async()=>({ok:true,json:async()=>doc})});
assert.equal(read.clubId,"10777");
await assert.rejects(()=>loadSpvggRoster({fetchImpl:async()=>({ok:false})}));
console.log("SpVgg official active roster: 5 teams, 50 mentions, 45 unique names, filters and provenance OK");
