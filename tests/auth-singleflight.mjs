import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {createAuthSingleflight} from "../scripts/auth-singleflight.mjs";
const source=await readFile("private-invites.js","utf8");
let releases,refreshCount=0;
const blocker=new Promise(resolve=>{releases=resolve;});
const run=createAuthSingleflight(async create=>{
 refreshCount++;
 await blocker;
 return {access_token:"synthetic-refresh",mode:create};
});
const pending=Array.from({length:25},()=>run(false));
assert.equal(refreshCount,1,"Simultaneous modules must issue one refresh");
assert.ok(pending.every(p=>p===pending[0]),"All concurrent callers share the same request");
releases();
const resolved=await Promise.all(pending);
assert.ok(resolved.every(p=>p.access_token==="synthetic-refresh"));
const again=await run(true);
assert.equal(again.mode,true);
assert.equal(refreshCount,2,"Next request after completion must work");
let rejectNow;
const failFirst=createAuthSingleflight(()=>new Promise((_,reject)=>{rejectNow=reject;}));
const failed=failFirst();
rejectNow(Error("conflict"));
await assert.rejects(failed,/conflict/);
assert.match(source,/createAuthSingleflight/);
assert.match(source,/navigator\.locks\?\.request/);
assert.match(source,/r\.status===409/);
assert.match(source,/newer\.refresh_token!==previousToken/);
assert.match(source,/throw Error\("Die Sitzung wird gleichzeitig aktualisiert/);
assert.doesNotMatch(source,/if\(r\.status===409\)\s*\{\s*localStorage\.removeItem/);
assert.match(source,/if\(\[400,401,403\]\.includes\(r\.status\)\)/);
console.log("Auth refresh singleflight and fail-closed HTTP 409 handling: passed");
