import assert from "node:assert/strict";
import {SIZE,DURATION_MS,MODE_VERSION,newSnake,placeFood,turnSnake,stepSnake} from "../games/snake.mjs";
assert.equal(SIZE,20);assert.equal(DURATION_MS,120000);assert.equal(MODE_VERSION,1);
const init=newSnake(()=>0);
assert.deepEqual(init.snake,[{x:10,y:10},{x:9,y:10},{x:8,y:10}]);
assert.ok(!init.snake.some(x=>x.x===init.food.x&&x.y===init.food.y));
assert.deepEqual(placeFood(Array.from({length:400},(_,i)=>({x:i%20,y:Math.floor(i/20)}))),null);
assert.equal(turnSnake(init,"left"),init,"reverse is ignored");
assert.equal(turnSnake(init,"invalid"),init);
const queued=turnSnake(init,"up");
assert.equal(turnSnake(queued,"left"),queued,"only one turn per tick");
assert.deepEqual(stepSnake(queued).snake[0],{x:10,y:9});
const after=stepSnake(queued);
assert.equal(after.turnQueued,false);
assert.equal(turnSnake(after,"left").queued,"left");
let wall={...init,snake:[{x:19,y:4},{x:18,y:4}],food:{x:1,y:1}};
assert.equal(stepSnake(wall).reason,"wall");
assert.equal(stepSnake(wall).score,0);
let body={...init,snake:[{x:3,y:3},{x:3,y:4},{x:4,y:4},{x:4,y:3},{x:5,y:3}],direction:"right",queued:"right",food:{x:0,y:0}};
assert.equal(stepSnake(body).reason,"body");
const eat={...init,food:{x:11,y:10}};
const ate=stepSnake(eat,()=>0);
assert.equal(ate.score,10);assert.equal(ate.snake.length,4);
assert.ok(!ate.snake.some(x=>x.x===ate.food.x&&x.y===ate.food.y));
const tail={...init,snake:[{x:2,y:2},{x:2,y:3},{x:3,y:3},{x:3,y:2}],direction:"right",queued:"right",food:{x:0,y:0}};
assert.equal(stepSnake(tail).over,false,"entering departing tail is legal");
assert.deepEqual(stepSnake({...init,over:true,reason:"time"}),{...init,over:true,reason:"time"});
console.log("F10 Snake pure rules: 20x20, 120s, turn guard, collision, food, tail, score OK");
