import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {matchAvailability} from "../scripts/match-availability.mjs";

const good=matchAvailability({});
assert.equal(good.retry,false);
assert.match(good.emptyNote,/Noch keine einzeln belegten Spiele verfügbar/);
const official=matchAvailability({officialFailed:true});
assert.equal(official.retry,true);
assert.match(official.emptyNote,/teilweise/);
assert.match(official.detail,/offizielle/);
assert.doesNotMatch(official.emptyNote,/keine.*Spiele/i);
const external=matchAvailability({externalFailed:true});
assert.equal(external.retry,true);
assert.match(external.detail,/Badhub/);
assert.match(external.detail,/nicht.*keine Matches/);
const both=matchAvailability({externalFailed:true,officialFailed:true});
assert.equal(both.retry,true);
assert.match(both.emptyNote,/nicht erreichbar/);
assert.doesNotMatch(both.emptyNote,/keine.*Spiele/i);
const html=await readFile("index.html","utf8");
const stats=await readFile("stats.js","utf8");
const css=await readFile("design-v2.css","utf8");
const sw=await readFile("sw.js","utf8");
assert.match(html,/id="match-stats-source-link"[^>]*rel="noopener noreferrer"[^>]*target="_blank"[^>]*hidden/);
assert.match(css,/\.match-stats-lookup\[hidden\]\{display:none!important\}/);
assert.match(stats,/\^\\d\{2\}-\\d\{6\}\$/);
assert.match(stats,/lookup\.hidden=!validId/);
assert.match(sw,/scripts\/match-availability\.mjs/);
console.log("Match availability v42: zero data differs from partial or complete source outage; safe cross-check and retry.");
