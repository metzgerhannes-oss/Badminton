// This neutral index is generated by the official club-source monitor.
async function verifiedClubLinks(team){
 if(team?.club_id!=="10777")return [];
 const response=await fetch("./data/team-report-links.json",{cache:"no-store"});
 if(!response.ok)throw Error("team_report_index");
 const feed=await response.json();
 if(feed?.schemaVersion!==1||feed.sourceKind!=="verified_official_team_report_links"||
  !Array.isArray(feed.reports)||feed.reports.length>160)throw Error("team_report_index_format");
 return feed.reports.filter(a=>{
  if(a?.club_id!=="spvgg-moessingen"||a?.source_id!=="club-moessingen")return false;
  try{
   const url=new URL(a.url);
   return url.protocol==="https:"&&["spvgg.org","www.spvgg.org"].includes(url.hostname)&&
    /^\/abteilungen\/badminton\/aktuelles\/[a-z0-9-]+\/?$/.test(url.pathname)&&
    (a.published_on===null||/^\d{4}-\d{2}-\d{2}$/.test(a.published_on));
  }catch{return false}
 }).map(a=>({url:a.url,title:"Mannschaftsbericht der SpVgg Mössingen",
  published_on:a.published_on,summary:"Originalbericht auf der Vereinswebsite",
  club_id:a.club_id}));
}
async function loadTeamReports(team){
 const ticket=++reportTicket;
 reportRows=[];reportState=window.badmintonAppAccess?.allowed?"loading":"restricted";renderTeamReports();
 if(reportState==="restricted")return;
 const articleClub=team.club_id==="10777"?"spvgg-moessingen":team.club_id;
 const access=async()=>{
  const token=await window.badmintonAppAccess.getAccessToken();
  if(!token)throw Error("no_member_token");
  const ctrl=new AbortController(),timeout=setTimeout(()=>ctrl.abort(),9000);
  try{
   const response=await fetch(SUPABASE_ROOT+"rpc/app_access_reports_read",{
    method:"POST",cache:"no-store",signal:ctrl.signal,
    headers:{apikey:PUBLIC_KEY,Authorization:"Bearer "+token,"Content-Type":"application/json"},
    body:JSON.stringify({p_player_dbv_id:null,p_invitation_id:null})
   });
   if(!response.ok)throw Error("report_http");
   const data=await response.json();
   if(data?.scope!=="member"||!Array.isArray(data.articles))throw Error("invalid_report_response");
   return data.articles.filter(a=>a.club_id===articleClub&&safeReportLink(a.url)&&typeof a.title==="string");
  }finally{clearTimeout(timeout)}
 };
 const results=await Promise.allSettled([access(),verifiedClubLinks(team)]);
 if(ticket!==reportTicket)return;
 if(results.every(r=>r.status==="rejected")){
  reportState="error";renderTeamReports();return;
 }
 const stored=results[0].status==="fulfilled"?results[0].value:[];
 const found=results[1].status==="fulfilled"?results[1].value:[];
 const merged=new Map();
 for(const row of [...found,...stored]){
  const link=safeReportLink(row.url);
  if(link)merged.set(link.replace("://www.","://").replace(/\/$/,""),row);
 }
 reportRows=[...merged.values()].sort((a,b)=>
  String(b.published_on||"").localeCompare(String(a.published_on||""))).slice(0,160);
 reportState="ready";renderTeamReports();
}

